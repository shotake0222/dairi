/**
 * 会話の入力に対する、最小限の安全ガード（フェーズ5「不適切な入力への対応」）。
 *
 * これまでは方針が無く、実質「モデル任せ」だった。ここで決めた方針は2段構え:
 *
 * 1. **自傷・自殺をほのめかす発言だけは、AIの生成に任せない。**
 *    キャラクターらしい返答を毎回AIに作らせると、平均的にはそれっぽい応答になるが、
 *    「たまたま軽く流してしまう」を許さない領域がある。ここだけは、
 *    運営が文面を選んだ固定の応答を必ず返す。相談窓口の案内は本物の公的機関のものを使う
 *    （2026年時点の情報は README のコメント、または `docs/` 側の参照に準じる。
 *    窓口の番号・運用が変わったら、ここを直接書き換えること）。
 * 2. **それ以外の不適切な入力**（性的な要求・暴力の助長・違法行為の相談など）は、
 *    検知して特別扱いするほど機械的に判定しやすくない（誤検知が多すぎる）ため、
 *    人格の一貫性を保ったまま断る、という方針を `src/ai/promptBuilder.ts` の
 *    `SAFETY_RULES` としてシステムプロンプトに持たせている。ここでは扱わない。
 *
 * 検知は単純な正規表現によるもので、完全ではない（誤検知・見逃しの両方がありうる）。
 * それでも「何もしていない」よりは十分に価値がある、という判断でここに置く。
 *
 * プライバシー上の注意: 検知したかどうかは集計（件数）だけを記録し、
 * **メッセージの本文はログに一切出さない**（既存方針を踏襲）。
 */

/**
 * 自傷・自殺のサイン。日本語の代表的な言い回しをいくつか押さえる。
 * 「死にたい」で完全一致させず、否定形（「死にたいわけじゃない」等）まで拾ってしまうのは
 * 誤検知として許容する——見逃すより、余計に1回ケアの言葉が出るほうが安全な方向だから。
 */
const SELF_HARM_PATTERNS: RegExp[] = [
  /死にたい/,
  /消えたい/,
  /自殺/,
  /自傷/,
  /リストカット/,
  /生きて(る|い)意味.*ない/,
  /生きてる(のが|の)?つらい/,
  /もう(疲れた|限界)[。、!！\s]*(死|消え)/,
];

/** 自傷・自殺をほのめかす内容が含まれているか。 */
export function detectsSelfHarmSignal(message: string): boolean {
  return SELF_HARM_PATTERNS.some((re) => re.test(message));
}

