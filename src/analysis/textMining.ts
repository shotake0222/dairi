/**
 * 会話からの語の抽出（テキストマイニング）。
 *
 * 方針:
 * Workers上で形態素解析器（kuromoji等）を動かすのは、辞書のサイズと起動時間の面で現実的でない。
 * かといってAIに毎ターン抽出させるとコストが読めない。
 * そこで「日本語の表記の切れ目」を手がかりにした軽い抽出をここに置き、
 * **無料で毎ターン回せる層**として使う。意味の理解が要る部分（価値観の推定など）は
 * src/analysis/psychographics.ts のAI抽出に任せる、という二段構えにしている。
 *
 * 精度は形態素解析に劣るが、目的は「この人がよく口にする語」を数えることなので、
 * 漢字の連なり・カタカナの連なり・英単語を拾えれば実用上は足りる。
 */

/** 数えても意味が無い語。日本語の会話で頻出するが話題を表さないもの。 */
const STOPWORDS = new Set([
  "自分", "今日", "明日", "昨日", "今年", "今月", "本当", "感じ", "感じる", "思う", "思っ", "言う", "言っ",
  "人", "事", "物", "時", "所", "方", "為", "中", "上", "下", "前", "後", "何", "誰", "私", "僕", "俺",
  "そう", "これ", "それ", "あれ", "どれ", "ここ", "そこ", "あそこ", "とき", "こと", "もの", "ほう",
  "気持ち", "大丈夫", "ありがとう", "おはよう", "こんにちは", "こんばんは", "おやすみ", "ごめん",
  "普通", "最近", "結構", "本当に", "多分", "一応", "全部", "少し", "沢山",
]);

/**
 * 語として扱う最小の長さ。
 *
 * 漢字だけは1文字でも拾う。「猫」「犬」「本」「夢」のように1文字で立派に話題になる語があり、
 * ここを2文字以上にすると、下の話題辞書に書いた「犬」「猫」が永久に当たらなくなる
 * （実際そうなっていた）。代わりに、1文字で頻出するが話題を表さない漢字は個別に落とす。
 * カタカナと英字は、1文字だと記号や略字ばかりなので2文字以上に限る。
 */
const MIN_KATAKANA_LENGTH = 2;
const MIN_LATIN_LENGTH = 2;

/** 1文字で頻出するが、話題を表さない漢字。 */
const SINGLE_KANJI_STOPWORDS = new Set([
  "人", "事", "物", "時", "所", "方", "中", "上", "下", "前", "後", "何", "私", "僕", "俺", "君",
  "気", "話", "日", "今", "分", "回", "点", "面", "目", "手", "足", "口", "年", "月", "週", "間",
  "一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "百", "千", "万", "億",
  "的", "性", "者", "化", "感", "系", "用", "内", "外", "全", "各", "他", "同",
]);

export interface TermCount {
  term: string;
  count: number;
}

/**
 * 1つの文字列から語の候補を切り出す。
 *
 * 拾うのは次の3種類:
 *   - 漢字の連なり（例: 電車通勤、資格試験）
 *   - カタカナの連なり（例: ゲーム、プログラミング）
 *   - アルファベットの語（例: Python、Vtuber）
 * ひらがなだけの語は、助詞や語尾と区別できないので取らない。
 */
export function extractTerms(text: string): string[] {
  if (!text) return [];
  const matches = text.match(/[一-鿿々]+|[ァ-ヶー]+|[A-Za-z][A-Za-z0-9+#.]*/g) ?? [];
  return matches
    .map((m) => m.trim())
    .filter((m) => {
      if (!m || STOPWORDS.has(m)) return false;
      if (/^[一-鿿々]+$/.test(m)) return m.length >= 2 || !SINGLE_KANJI_STOPWORDS.has(m);
      if (/^[ァ-ヶー]+$/.test(m)) return m.length >= MIN_KATAKANA_LENGTH;
      return m.length >= MIN_LATIN_LENGTH;
    });
}

/** 複数の発言をまとめて数え、多い順に返す。 */
export function countTerms(texts: string[], limit = 20): TermCount[] {
  const counts = new Map<string, number>();
  for (const text of texts) {
    for (const term of extractTerms(text)) {
      counts.set(term, (counts.get(term) ?? 0) + 1);
    }
  }
  return [...counts.entries()]
    .map(([term, count]) => ({ term, count }))
    // 同数のときは長い語を優先する（「試験」より「資格試験」の方が話題として具体的なため）
    .sort((a, b) => b.count - a.count || b.term.length - a.term.length)
    .slice(0, limit);
}

/**
 * 語の出現を、あらかじめ決めた話題カテゴリへ寄せる。
 *
 * セグメンテーションで使うため、語そのものではなくカテゴリの重みに変換する。
 * 語彙表は網羅ではなく「よく出る入口の語」だけを置き、当たらない語は無視する
 * （当たらない語を無理にどこかへ入れると、セグメントが濁る）。
 */
export const TOPIC_LEXICON: Record<string, string[]> = {
  仕事: ["仕事", "会社", "職場", "上司", "同僚", "残業", "転職", "会議", "出社", "在宅", "案件", "業務", "給料"],
  勉強: ["勉強", "試験", "資格", "学校", "大学", "授業", "課題", "受験", "研究", "論文"],
  健康: ["体調", "睡眠", "疲れ", "運動", "筋トレ", "散歩", "病院", "food", "食事", "ダイエット", "ヨガ"],
  趣味創作: ["絵", "イラスト", "写真", "カメラ", "music", "音楽", "ギター", "小説", "創作", "編み物", "DIY"],
  エンタメ: ["ゲーム", "アニメ", "漫画", "マンガ", "映画", "ドラマ", "配信", "推し", "ライブ", "アイドル", "Vtuber"],
  食: ["料理", "ごはん", "ラーメン", "カフェ", "コーヒー", "お菓子", "外食", "弁当", "パン"],
  旅行: ["旅行", "temple", "旅", "電車", "新幹線", "海", "山", "温泉", "観光", "散策"],
  人間関係: ["友達", "家族", "恋人", "彼氏", "彼女", "親", "子供", "子ども", "喧嘩", "結婚", "職場恋愛"],
  技術: ["プログラミング", "コード", "開発", "Python", "JavaScript", "AI", "機械学習", "サーバー", "アプリ"],
  お金: ["投資", "株", "貯金", "節約", "家計", "副業", "税金", "ローン"],
  動物: ["犬", "猫", "ペット", "うさぎ", "金魚", "散歩犬", "動物"],
  気分: ["不安", "しんどい", "落ち込", "嬉しい", "楽しい", "寂しい", "緊張", "焦り", "幸せ"],
};

/** 語の出現から、話題カテゴリごとの重み（0以上）を作る。 */
export function topicWeights(terms: TermCount[]): Record<string, number> {
  const weights: Record<string, number> = {};
  for (const { term, count } of terms) {
    for (const [topic, lexicon] of Object.entries(TOPIC_LEXICON)) {
      // 部分一致で拾う（「資格試験」が「試験」に当たるようにするため）
      if (lexicon.some((word) => term.includes(word) || word.includes(term))) {
        weights[topic] = (weights[topic] ?? 0) + count;
      }
    }
  }
  return weights;
}
