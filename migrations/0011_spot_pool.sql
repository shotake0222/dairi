-- 配布元ごとの「そこでしか出ない姿」。
--
-- **これまでの決めごとを、意図して一段だけ緩める。**
--
-- 0009 には「運営が姿を決められる仕組みは置かない」と書いた。理由は変わっていない——
-- 運営が individual を決められると、手に入れた喜びが「引き当てた」ではなく「配られた」になる。
--
-- そのうえで、場所限定の姿を作れるようにする。両立させるために、決められる範囲を分けた。
--
--   決められる   … **どの範囲から引くか**（例: この神社のQRからは「きらつぶ」しか出ない）
--   決められない … **その範囲の中で、どの子が出るか**（引くのは今までどおりDO側の乱数）
--
-- つまり運営が細くできるのは母集団だけで、抽選そのものには手を出せない。
-- 「ここでしか会えない姿だが、色までは選べない」という形になり、引く体験は残る。
--
-- 変わらない決めごと:
--   - 1つの依代からは1体だけ
--   - 範囲を指定していない配布元（＝ほとんど）は、これまでどおり30種類から等確率
--   - 直接追加（/add）には限定の姿を出さない。場所へ行った意味が消えるため
--
-- 空（NULL または空文字）なら「制限なし」。カンマ区切りで複数指定できる。
-- 種族だけ絞る／色だけ絞る／両方絞る、のいずれも可。
